# Scenario rendering
# ----------------------------------------------------------------------


def _noise(rng: np.random.Generator, shape: Tuple[int, int], sigma: float = 0.02):
    return 1.0 + rng.normal(0.0, sigma, shape)


def _render(
    classes: np.ndarray,
    seed: int,
    shape: Tuple[int, int],
) -> Tuple[Dict[str, np.ndarray], np.ndarray]:
    """Render reflectance bands and an SCL grid from a surface-class map."""
    rng = np.random.default_rng(seed)
    bands: Dict[str, np.ndarray] = {}
    for band in BANDS:
        plane = np.zeros(shape, dtype=np.float64)
        for name, values in _SURFACE_REFLECTANCE.items():
            selected = classes == name
            if selected.any():
                plane[selected] = values[band]
        bands[band] = np.maximum(plane * _noise(rng, shape), 1.0)

    scl = np.zeros(shape, dtype=np.uint8)
    for name, code in _SCL_CLASS.items():
        scl[classes == name] = code
    return bands, scl


def _rect(shape: Tuple[int, int], row0: float, col0: float, height: float, width: float) -> np.ndarray:
    """Axis-aligned rectangle in fractional grid coordinates."""
    rows, cols = shape
    r0, r1 = int(row0 * rows), int((row0 + height) * rows)
    c0, c1 = int(col0 * cols), int((col0 + width) * cols)
    out = np.zeros(shape, dtype=bool)
    out[max(r0, 0):min(r1, rows), max(c0, 0):min(c1, cols)] = True
    return out


def _base_classes(
    scenario: str, shape: Tuple[int, int], rng: np.random.Generator
) -> np.ndarray:
    """The undisturbed surface present before the scenario's event."""
    classes = np.full(shape, "vegetation", dtype=object)

    if scenario in ("glacier_retreat",):
        classes[:] = "snow"
        classes[_rect(shape, 0.0, 0.0, 0.30, 1.0)] = "bare"
    elif scenario in ("reservoir_expansion", "coastal_flooding"):
        classes[:] = "bare"
        classes[_rect(shape, 0.55, 0.0, 0.45, 1.0)] = "water"
        classes[_rect(shape, 0.0, 0.70, 0.25, 0.30)] = "built_up"
    else:
        classes[_rect(shape, 0.60, 0.0, 0.40, 1.0)] = "water"
        classes[_rect(shape, 0.05, 0.05, 0.20, 0.20)] = "bare"
    return classes


def _apply_event(
    scenario: str, classes: np.ndarray, rng: np.random.Generator
) -> Tuple[np.ndarray, np.ndarray, str]:
    """
    Apply the scenario's event, returning the new class map, the ground-truth change
    mask, and a plain description of what was applied.
    """
    shape = classes.shape
    updated = classes.copy()
    truth = np.zeros(shape, dtype=bool)

    if scenario == "new_construction":
        patch = _rect(shape, 0.30, 0.30, 0.22, 0.22)
        updated[patch] = "built_up"
        truth |= patch
        description = "a new built-up construction site appeared"

    elif scenario == "glacier_retreat":
        # The margin becomes exposed bare ground: snow and ice lost, rock revealed.
        exposed = _rect(shape, 0.26, 0.0, 0.10, 1.0)
        updated[exposed] = "bare"
        truth |= exposed
        description = "the snow and ice margin retreated, exposing bare ground"

    elif scenario == "reservoir_expansion":
        flooded = _rect(shape, 0.40, 0.0, 0.18, 1.0)
        updated[flooded] = "water"
        truth |= flooded
        description = "open water expanded upstream"

    elif scenario == "coastal_flooding":
        inundated = _rect(shape, 0.45, 0.10, 0.25, 0.80)
        updated[inundated] = "water"
        truth |= inundated
        description = "flood water inundated low-lying land"

    else:
        raise DemoError(f"Unknown DEMO scenario '{scenario}'")

    return updated, truth, description


def build_demo_dataset(
    aoi: Optional[AOI] = None,
    bounds: Optional[Tuple[float, float, float, float]] = None,
    monitoring_mode: Optional[str] = None,
    scenario: str = "new_construction",
    baseline_date: Optional[datetime] = None,
    interval_days: int = 15,
    shape: Tuple[int, int] = (200, 200),
    crs: str = "EPSG:4326",
    seed: int = 20240610,
    name: Optional[str] = None,
) -> DemoDataset:
    """
    Build a labelled synthetic comparison for any AOI.

    The returned `truth_mask` records exactly which pixels were changed by the scenario,
    so detector output can be scored against ground truth instead of merely inspected.
    """
    if aoi is None:
        if bounds is None:
            raise DemoError("Provide either an AOI or explicit bounds for a DEMO dataset")
        mode = MonitoringMode(monitoring_mode or "general")
        aoi = build_aoi(bbox=list(bounds), monitoring_mode=mode)

    mode = MonitoringMode(monitoring_mode or aoi.monitoring_mode.value)
    if scenario not in _SUPPORTED_SCENARIOS:
        raise DemoError(
            f"Unknown DEMO scenario '{scenario}'. Supported: {sorted(_SUPPORTED_SCENARIOS)}"
        )

    bounds = tuple(aoi.geometry.bounds)
    width, height = shape
    transform = GeoTransform.from_bounds(bounds, width, height)

    # AOI geometry is honoured: pixels outside it are not part of the demonstration.
    inside = aoi.mask_for(transform, (height, width))

    rng = np.random.default_rng(seed)
    baseline_classes = _base_classes(scenario, shape, rng)
    current_classes, event_region, description = _apply_event(
        scenario, baseline_classes, rng
    )
    current_classes = np.where(inside, current_classes, baseline_classes)

    # Ground truth is the set of pixels whose surface actually changed, not the whole
    # event rectangle. Part of an event region may already have been the target surface,
    # and counting those pixels would understate the detector for no good reason.
    changed = baseline_classes != current_classes
    truth_mask = changed & inside & event_region

    baseline = datetime(2024, 6, 10, tzinfo=timezone.utc) if baseline_date is None else baseline_date
    if baseline.tzinfo is None:
        baseline = baseline.replace(tzinfo=timezone.utc)

    baseline_bands, baseline_scl = _render(baseline_classes, seed, shape)
    current_bands, current_scl = _render(current_classes, seed + 1, shape)

    # Outside the requested AOI the two scenes must be bit-identical. The AOI is what the
    # user asked to monitor, so nothing beyond it may vary between the pair; leaving the
    # independent noise field in place would show up as change the user never requested.
    for band in BANDS:
        current_bands[band][~inside] = baseline_bands[band][~inside]
    current_scl[~inside] = baseline_scl[~inside]

    baseline_scene = DemoScene(
        captured=baseline,
        bands=baseline_bands,
        scl=baseline_scl,
        description=f"Synthetic pre-event scene ({scenario}).",
    )
    current_scene = DemoScene(
        captured=baseline + timedelta(days=interval_days),
        bands=current_bands,
        scl=current_scl,
        description=f"Synthetic scene {interval_days} days later in which {description}.",
    )

    return DemoDataset(
        name=name or f"{aoi.id}_{scenario}",
        aoi=aoi,
        transform=transform,
        crs=crs,
        baseline=baseline_scene,
        current=current_scene,
        truth_mask=truth_mask,
        scenario=scenario,
        notes=(
            f"{description}. Ground truth: "
            f"{int(np.count_nonzero(truth_mask))} changed pixels."
        ),
    )


_SUPPORTED_SCENARIOS = {
    "new_construction", "glacier_retreat", "reservoir_expansion", "coastal_flooding",
}


def scenarios_for_mode(mode: str) -> List[str]:
    """Scenarios that make sense for a monitoring mode."""
    mapping = {
        MonitoringMode.GENERAL.value: ["new_construction", "coastal_flooding"],
        MonitoringMode.INFRASTRUCTURE.value: ["new_construction", "coastal_flooding"],
        MonitoringMode.GLACIER.value: ["glacier_retreat"],
        MonitoringMode.WATER_BODY.value: ["reservoir_expansion"],
        MonitoringMode.FLOOD.value: ["coastal_flooding"],
        MonitoringMode.VEGETATION.value: ["new_construction"],
    }
    return mapping.get(str(mode), ["new_construction"])