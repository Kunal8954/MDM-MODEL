"""
satguard/processing/demo.py
Deterministic, explicitly synthetic demonstration data.

Purpose and limits
------------------
DEMO mode exists so the product can be explored without Sentinel credentials. It renders
synthetic rasters that are physically plausible and georeferenced to a real location, so
the whole pipeline can be exercised end to end.

These are **not satellite observations**. Every artefact produced here carries
`source="DEMO"` and `synthetic=True`, and each scene ships the ground-truth mask it was
built from so the detector's output can be checked against a known answer.

DEMO data is never a fallback for LIVE mode: if credentials are missing, LIVE must fail
loudly rather than quietly returning synthetic results.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from typing import Any, Dict, List, Optional, Tuple

import numpy as np

from satguard.geospatial.area_of_interest import AOI, MonitoringMode, build_aoi
from satguard.geospatial.raster import GeoTransform
from satguard.processing.preprocess import build_quality_mask

logger = logging.getLogger("satguard.demo")

DEMO_SOURCE = "DEMO"

# Reflectance-like values for the surface classes used to build scenes. These are
# plausible Sentinel-2 L2A surface reflectance values by relative magnitude; they are
# synthetic and are not calibrated to any real acquisition.
_SURFACE_REFLECTANCE: Dict[str, Dict[str, float]] = {
    # dark, strongly absorbing in SWIR: open water
    "water":    {"B02": 280, "B03": 260, "B04": 240, "B06": 180, "B08": 110, "B11": 90,  "B12": 70},
    # moderate visible, high NIR: vegetation
    "vegetation": {"B02": 700, "B03": 900, "B04": 800, "B06": 2100, "B08": 3400, "B11": 2200, "B12": 1400},
    # bright visible and SWIR: bare rock and soil
    "bare":     {"B02": 1500, "B03": 1600, "B04": 1700, "B06": 2000, "B08": 1900, "B11": 2500, "B12": 2300},
    # high visible, low NIR/SWIR: built-up surfaces
    "built_up": {"B02": 1900, "B03": 2000, "B04": 2100, "B06": 2300, "B08": 2000, "B11": 2600, "B12": 2400},
    # very high visible, very low NIR/SWIR: snow and ice
    "snow":     {"B02": 2900, "B03": 3100, "B04": 3200, "B06": 1700, "B08": 900,  "B11": 500,  "B12": 300},
}

# Sentinel-2 Scene Classification Layer codes. Snow and ice is class 11; class 3 is
# cloud shadow, so labelling ice as 3 would discard the entire glacier as unusable.
_SCL_CLASS: Dict[str, int] = {
    "water": 6, "vegetation": 4, "bare": 5, "built_up": 5, "snow": 11,
}

BANDS: Tuple[str, ...] = ("B02", "B03", "B04", "B06", "B08", "B11", "B12")


class DemoError(Exception):
    error_code = "DEMO_GENERATION_FAILED"


@dataclass
class DemoScene:
    """One synthetic scene, with the truth that was used to build it."""
    captured: datetime
    bands: Dict[str, np.ndarray]
    scl: np.ndarray
    description: str
    synthetic: bool = True
    source: str = DEMO_SOURCE

    def quality_mask(self, monitoring_mode: Optional[str] = None) -> "Any":
        """
        Build the usable-data mask for this scene.

        The monitoring mode matters: SCL class 3 is snow and ice, which is unusable for
        most monitoring but is exactly the subject of glacier monitoring. Masking it
        unconditionally would leave a glacier comparison with no valid snow pixels.
        """
        mask = build_quality_mask(self.scl, self.scl.shape)
        return mask.reject_for_mode(monitoring_mode) if monitoring_mode else mask

    def to_dict(self) -> Dict[str, Any]:
        return {
            "captured": self.captured.isoformat(),
            "description": self.description,
            "synthetic": self.synthetic,
            "source": self.source,
            "shape": list(self.scl.shape),
        }


@dataclass
class DemoDataset:
    """
    A georeferenced pair of synthetic scenes plus the ground truth describing what
    actually changed between them.
    """
    name: str
    aoi: AOI
    transform: GeoTransform
    crs: str
    baseline: DemoScene
    current: DemoScene
    truth_mask: np.ndarray
    scenario: str
    notes: str = ""
    synthetic: bool = True
    source: str = DEMO_SOURCE

    @property
    def truth_area_m2(self) -> float:
        return float(np.count_nonzero(self.truth_mask) * _pixel_area(self.transform))

    def to_dict(self) -> Dict[str, Any]:
        """Manifest. Everything a reviewer needs to know this data is synthetic."""
        return {
            "name": self.name,
            "scenario": self.scenario,
            "source": self.source,
            "synthetic": self.synthetic,
            "disclaimer": (
                "Synthetic demonstration data generated by satguard.processing.demo. "
                "These are not satellite observations and must not be used for any "
                "operational, regulatory or safety decision."
            ),
            "aoi": self.aoi.to_dict(),
            "crs": self.crs,
            "grid": {
                "width": int(self.baseline.scl.shape[1]),
                "height": int(self.baseline.scl.shape[0]),
            },
            "baseline": self.baseline.to_dict(),
            "current": self.current.to_dict(),
            "truth": {
                "changed_pixels": int(np.count_nonzero(self.truth_mask)),
                "changed_area_m2": round(self.truth_area_m2, 2),
                "changed_area_km2": round(self.truth_area_m2 / 1e6, 6),
            },
            "notes": self.notes,
        }


def _pixel_area(transform: GeoTransform) -> float:
    """Square metres per pixel, using the raster's own centre latitude."""
    return transform.pixel_area_m2(transform.f + transform.e / 2.0)


